"""Render docs/JOTFORM_MAPPING.md from the versioned mapping + form snapshot.

    python scripts/render_mapping_doc.py
"""
from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
MAP_DIR = ROOT / "backend" / "app" / "mapping"
OUT = ROOT / "docs" / "JOTFORM_MAPPING.md"


def main() -> None:
    m = json.loads((MAP_DIR / "jotform_252413844700855.mapping.json").read_text())
    s = json.loads((MAP_DIR / "form_252413844700855.snapshot.json").read_text())
    fields = {f["qid"]: f for f in s["fields"]}

    def inputs(qid: str) -> str:
        f = fields[qid]
        return "<br>".join(f"`{i['name']}`{' **(required)**' if i['required'] else ''}" for i in f["inputs"]) or "-"

    def record(e: dict) -> str:
        r = e.get("record")
        if isinstance(r, dict):
            return "<br>".join(f"{k} ← `{v}`" for k, v in r.items())
        if r:
            return f"`{r}`"
        return {"description": "composed summary + outcome + other details + ref",
                "upload": "manual: attach in Jotform"}.get(e["transform"], "-")

    def row(e: dict) -> str:
        f = fields[e["qid"]]
        label = e.get("label_override") or f["label"]
        opts = f" (options: {', '.join(f['options'])})" if f["options"] else ""
        return f"| {e['qid']} | {label}{opts} | {f['type'].replace('control_', '')} | {inputs(e['qid'])} | {e['transform']} | {record(e)} |"

    hdr = "| QID | Jotform label | Type | Input name(s) | Transform | ConstitBrief source |\n|---|---|---|---|---|---|"
    lines = [
        "# Jotform mapping: Web OfficeOne (form 252413844700855)",
        "",
        "_Generated by `scripts/render_mapping_doc.py`. Do not edit by hand._",
        "",
        f"* **Mapping version:** `{m['mapping_version']}`",
        f"* **Form:** <{m['form_url']}> (embedded on julieanncampbell.com.au as “Web OfficeOne”)",
        f"* **Snapshot captured:** {s['captured_at']} from the public form HTML, structure hash `{s['structure_sha256'][:16]}…`",
        "* **Re-verify:** `python scripts/snapshot_jotform.py --check` (fails if the live form structure changed)",
        "",
        "## Verification status",
        "",
        "| Aspect | Status |", "|---|---|",
        *[f"| {k.replace('_', ' ').capitalize()} | {v} |" for k, v in m["verification"].items()],
        "",
        "> **Email routing (the five destinations) is NOT verified.** Notification settings are not",
        "> visible on the public form. ConstitBrief does not send email and never submits server-side,",
        "> so whatever routing Jotform applies to a normal browser submission is preserved, but which",
        "> option reaches which destination still needs to be confirmed from the Jotform account.",
        "",
        "## How the form branches",
        "",
        f"Field {m['type_field']['qid']} “{m['type_field']['label']}” (`typeA`) shows one section per option. "
        "Required checks in hidden sections are not enforced in the browser. Whether values typed into a "
        "hidden section are kept on submit is a form setting that hasn't been verified.",
        "",
        "| Option (`typeA`) | Section | Shown by condition |", "|---|---|---|",
    ]
    for opt, b in m["branches"].items():
        shown = any(a["field"] == b["section"] and any(t["value"] == opt for t in c["terms"])
                    for c in s["conditions"] for a in c["actions"])
        lines.append(f"| {opt} | {b['section']} | {'yes' if shown else '**no**'} |")
    lines += ["", "## Always-shown fields", "", hdr, *[row(e) for e in m["common"]], ""]
    for d in m["declarations"]:
        lines += [f"Declaration (field {d['qid']}): _“{d['text']}”_", ""]
    lines += ["There is **no consent or authority field** on the form.", ""]
    for opt, b in m["branches"].items():
        lines += [f"## {opt}", "", hdr, *[row(e) for e in b["fields"]], ""]
    lines += [
        "## Transformation rules", "",
        "* `fullname` / `address`: record fields copied into the named sub-inputs. A blank address state defaults to `QLD`, and staff see that default in the record.",
        "* `date_mdy`: ISO date split into `[month]`, `[day]`, `[year]` sub-inputs, shown to staff as DD/MM/YYYY.",
        "* `date_text`: ISO date rendered as DD/MM/YYYY into a plain text field (ATO date of birth).",
        "* `choice`: only sent if the value is exactly one of the form's options. Otherwise left blank.",
        "* `description`: the branch's free-text field gets the staff summary, requested outcome, record",
        "  details with no dedicated field, staff-approved actions and confirmed deadlines, then",
        "  `ConstitBrief ref: CB-XXXXXX-n`. The reference lets an optional read-only API check confirm the submission.",
        "* `upload`: can't be prefilled. Staff attach the files in Jotform.",
        "",
        "## URL policy", "",
        "Only `typeA` (the enquiry option) is placed in the Jotform URL by default. Contact details are added only if",
        "`JOTFORM_PREFILL_CONTACT=true` (an office decision). Notes, descriptions, identifiers and dates are never put in a URL.",
        "",
        "## Known form issues", "",
        *[f"* {x}" for x in m["known_form_issues"]],
        "",
    ]
    OUT.parent.mkdir(exist_ok=True)
    OUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"Wrote {OUT}")


if __name__ == "__main__":
    main()
